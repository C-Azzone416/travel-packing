// Usage: tsx scripts/build-airports.ts <airports.csv>
// Rebuilds src/server/airports/airports-data.ts from the OurAirports airports.csv
// (https://davidmegginson.github.io/ourairports-data/airports.csv; public domain, see the header of that file).

import { readFileSync, writeFileSync } from "node:fs";
import { encodeAirports, selectAirports } from "../src/server/airports/build-dataset";

const input = process.argv[2];
if (!input) {
  console.error("Usage: tsx scripts/build-airports.ts <airports.csv>");
  process.exit(2);
}
const rows = selectAirports(readFileSync(input, "utf8"));
if (rows.length < 1000) {
  console.error(`Only ${rows.length} airports kept: is this the OurAirports airports.csv?`);
  process.exit(1);
}
const date = new Date().toISOString().slice(0, 10);
const output = `// Generated by scripts/build-airports.ts from OurAirports airports.csv on ${date}; do not edit by hand.
// Source: https://davidmegginson.github.io/ourairports-data/airports.csv (OurAirports, https://ourairports.com/data/).
// Licence: the data repository https://github.com/davidmegginson/ourairports-data carries the Unlicense, a public-domain
// dedication (https://unlicense.org); no attribution is required.
// Kept: airports with an IATA code and scheduled service, type large or medium (${rows.length} rows).
// SERVER ONLY: never import this from client code (scripts/check-client-bundle.ts looks for the marker below).

export const AIRPORT_DATA_MARKER = "ourairports-bundled-dataset";

export const AIRPORT_DATA =
  ${JSON.stringify(encodeAirports(rows))};
`;
writeFileSync("src/server/airports/airports-data.ts", output);
console.log(`wrote ${rows.length} airports`);
